"""Writes the walkthroughs that have a `docs` slug in content.py into a vaadin/docs checkout: each as an AsciiDoc
partial, articles/tools/copilot/features/_walkthrough-<slug>.adoc, and its clips and stills (light and -dark) under
src/main/resources/META-INF/resources/vaadin/videos/copilot/<slug>/. A walkthrough marked `sections` is written
as one partial per step instead, _<slug>-<step>.adoc with its text and clip, for a page that has a section of its
own for each step. The pages that include the partials are
written by hand in the docs repo; a re-record only changes what this writes.

usage: python3 -I docs-content/asciidoc.py . ../docs [scene…]   (after npm run walkthrough for both themes)

With scenes (e.g. 91-docs-edit-text), only their walkthroughs are written; npm run regenerate passes the ones it cut.
"""
import json
import os
import re
import shutil
import sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
from content import PAGES  # noqa: E402

repo, docs, only = sys.argv[1], sys.argv[2], set(sys.argv[3:])
ARTICLES = os.path.join(docs, "articles/tools/copilot/features")
MEDIA = os.path.join(docs, "src/main/resources/META-INF/resources/vaadin/videos/copilot")
URL = "{articles}/vaadin/videos/copilot"


def adoc(text):
    """content.py's markup in AsciiDoc: **bold**, [[what the clip outlines]], `code`."""
    text = re.sub(r"\*\*([^*]+)\*\*", r"*\1*", text)
    # Keys are kbd:[…], file names take the docs' filename role (CONVENTIONS.md).
    text = re.sub(r"`(Enter|Escape|Tab|Shift|Ctrl|Alt|Delete)`", r"kbd:[\1]", text)
    text = re.sub(r"`([\w.-]+\.(?:java|css|json|properties))`", r"[filename]#\1#", text)
    return re.sub(r"\[\[([^\]]+)\]\]", r"[.walkthrough-look]#\1#", text)


def plain(text):
    return re.sub(r"\*\*|\[\[|\]\]|`", "", text)


def steps_of(scene):
    manifest = os.path.join(repo, "out", scene, "steps", "steps.json")
    if not os.path.exists(manifest):
        sys.exit(f"{scene}: not cut yet (npm run walkthrough -- {scene})")
    return json.load(open(manifest))


def write(w):
    slug, light, dark = w["docs"], steps_of(w["scene"]), steps_of(w["scene"] + "-dark")
    if [s["name"] for s in light] != [s["name"] for s in dark] or set(w["steps"]) != {s["name"] for s in light}:
        sys.exit(f"{w['scene']}: the light and dark takes and content.py must have the same steps")
    dest = os.path.join(MEDIA, slug)
    shutil.rmtree(dest, ignore_errors=True)
    os.makedirs(dest)
    header = [
        f"// Generated by vaadin-copilot-demo-generator (docs-content/asciidoc.py) from the recorded walkthrough",
        f"// {w['scene']}. Change the step texts there (docs-content/content.py), not here; the clips are in {URL[len('{articles}/'):]}/{slug}/,",
        "// each with a -dark twin that dspublisher/theme/walkthrough.ts shows in the dark theme.",
        "",
    ]
    lines = header + ["[.walkthrough]", f".{w['title']}"]
    for theme, takes in (("", light), ("-dark", dark)):
        src = os.path.join(repo, "out", w["scene"] + theme, "steps")
        for s in takes:
            for f in (s["still"], s.get("video")):
                if f:
                    base, ext = os.path.splitext(f)
                    shutil.copy(os.path.join(src, f), os.path.join(dest, base + theme + ext))
    def media(s, text):
        if s.get("video"):
            return f'video::{URL}/{slug}/{s["video"]}[options="autoplay,loop,muted",poster="{URL}/{slug}/{s["still"]}"]'
        return f'image::{URL}/{slug}/{s["still"]}["{plain(text)}"]'

    if len(light) == 1:
        # One step: its text and its clip on their own, not a list of one.
        text = w["steps"][light[0]["name"]]
        body = [adoc(text), "", "[.walkthrough]", "--", media(light[0], text), "--"]
        with open(os.path.join(ARTICLES, f"_walkthrough-{slug}.adoc"), "w") as f:
            f.write("\n".join(header + body) + "\n")
    elif w.get("sections"):
        for s in light:
            text = w["steps"][s["name"]]
            # A clip on its own: the [.walkthrough] role gives it the walkthrough's frame and theme switch.
            body = [adoc(text), "", "[.walkthrough]", "--", media(s, text), "--"]
            with open(os.path.join(ARTICLES, f"_{slug}-{s['name']}.adoc"), "w") as f:
                f.write("\n".join(header + body) + "\n")
    else:
        for s in light:
            text = w["steps"][s["name"]]
            lines += [f". {adoc(text)}", "+", media(s, text)]
        with open(os.path.join(ARTICLES, f"_walkthrough-{slug}.adoc"), "w") as f:
            f.write("\n".join(lines) + "\n")
    size = sum(os.path.getsize(os.path.join(dest, f)) for f in os.listdir(dest))
    print(f"{slug}: {len(light)} steps, {size / 1e6:.1f} MB of media")


for page in PAGES:
    for w in page["walkthroughs"]:
        if w.get("docs") and (not only or w["scene"] in only):
            write(w)
